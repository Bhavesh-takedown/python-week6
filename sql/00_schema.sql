CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS etl;

CREATE TABLE IF NOT EXISTS raw.customer_stage (
    customer_id       text PRIMARY KEY,
    full_name         text NOT NULL,
    email             text NOT NULL,
    segment           text NOT NULL,
    city              text NOT NULL,
    source_updated_at timestamptz NOT NULL,
    profile           jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS raw.sales_stage (
    event_date   date NOT NULL,
    event_ts     timestamptz NOT NULL,
    sale_id      text NOT NULL,
    customer_id  text NOT NULL,
    product_id   text NOT NULL,
    quantity     integer NOT NULL CHECK (quantity > 0),
    unit_price   numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
    sale_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (sale_id, event_date),
    CHECK (event_date = (event_ts AT TIME ZONE 'UTC')::date)
);

CREATE TABLE IF NOT EXISTS dw.customer_dim (
    customer_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id text NOT NULL,
    full_name   text NOT NULL,
    email       text NOT NULL,
    segment     text NOT NULL,
    city        text NOT NULL,
    profile     jsonb NOT NULL DEFAULT '{}'::jsonb,
    valid_from  timestamptz NOT NULL,
    valid_to    timestamptz NOT NULL DEFAULT 'infinity'::timestamptz,
    is_current  boolean NOT NULL DEFAULT true,
    CHECK (valid_from < valid_to),
    CHECK (is_current = (valid_to = 'infinity'::timestamptz))
);

CREATE UNIQUE INDEX IF NOT EXISTS customer_dim_one_current_row
    ON dw.customer_dim (customer_id)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS customer_dim_history_idx
    ON dw.customer_dim (customer_id, valid_from DESC);

CREATE INDEX IF NOT EXISTS customer_dim_current_segment_city_idx
    ON dw.customer_dim (segment, city)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS customer_dim_profile_gin_idx
    ON dw.customer_dim USING gin (profile jsonb_path_ops);

CREATE TABLE IF NOT EXISTS dw.customer_change_audit (
    audit_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_sk bigint NOT NULL,
    customer_id text NOT NULL,
    action      text NOT NULL CHECK (action IN ('INSERT')),
    changed_at  timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS dw.fact_sales (
    event_date   date NOT NULL,
    event_ts     timestamptz NOT NULL,
    sale_id      text NOT NULL,
    customer_sk  bigint NOT NULL REFERENCES dw.customer_dim (customer_sk),
    product_id   text NOT NULL,
    quantity     integer NOT NULL CHECK (quantity > 0),
    unit_price   numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
    total_amount numeric(14, 2) NOT NULL,
    sale_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (sale_id, event_date),
    CHECK (event_date = (event_ts AT TIME ZONE 'UTC')::date)
) PARTITION BY RANGE (event_date);

CREATE TABLE IF NOT EXISTS dw.fact_sales_2025
    PARTITION OF dw.fact_sales
    FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');

CREATE TABLE IF NOT EXISTS dw.fact_sales_2026
    PARTITION OF dw.fact_sales
    FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

CREATE TABLE IF NOT EXISTS dw.fact_sales_default
    PARTITION OF dw.fact_sales DEFAULT;

CREATE INDEX IF NOT EXISTS fact_sales_customer_date_idx
    ON dw.fact_sales (customer_sk, event_date);

CREATE INDEX IF NOT EXISTS fact_sales_date_sale_idx
    ON dw.fact_sales (event_date, sale_id);
